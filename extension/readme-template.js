// The plain-language guide placed in every evidence pack as README.txt.
function ppReadme(o) {
  const stamps = o.stamps || [];
  const tsa = stamps.length > 0;
  return [
    'ABOUT THIS EVIDENCE PACK',
    '========================',
    '',
    'This folder is a record of the web page below, captured with PageProof ' + o.version + ',',
    'a browser extension.',
    '',
    '  Capture ID:   ' + (o.captureId || '(none)'),
    '  Web address:  ' + o.url,
    '  Captured:     ' + o.time + ' (UTC)',
    '',
    'EASIEST WAY TO CHECK THIS PACK',
    '------------------------------',
    'Double-click VERIFY-THIS-PACK.html. It opens in your web browser (no internet or',
    'installation needed). Drop this zip file onto it, or click "Choose the unzipped folder"',
    'and pick this folder. You get a green "Unchanged" or a red "Warning" result.',
    '',
    ...(o.notes && o.notes.length ? ['HOW THE CAPTURE WAS TAKEN',
      '--------------------------',
      ...o.notes.map(n => '- ' + n),
      ''] : []),
    'WHAT EACH FILE IS',
    '-----------------',
    '',
    o.base + '.pdf',
    '    A picture of the whole page, top to bottom, exactly as it appeared on screen.',
    '    The banner at the top shows the website address, page title, capture time,',
    '    time zone and browser window size. Parts of the page that scrolled on their own',
    '    are marked "Section 1", "Section 2"... and shown in full at the end.',
    '',
    o.base + '.html',
    '    A copy of the page as the browser displayed it. Pictures, styles and fonts are',
    '    stored inside the file, so it opens in any browser even if the website removes them.',
    '',
    ...(o.hasSource ? [o.base + '_source.html',
      '    The page source exactly as the website\'s server sent it (it may look unstyled',
      '    when opened). The server\'s address and response details are in capture-details.txt.',
      ''] : []),
    ...(o.imageCount ? ['images/',
      '    The original image files (' + o.imageCount + ') downloaded from the page. Where each came',
      '    from is listed in capture-details.txt.',
      ''] : []),
    ...(o.imageData ? ['image-data.txt',
      '    The hidden data found inside each of those image files: camera, date, place,',
      '    editing software, author and copyright notice. ' + o.imageData,
      '    Many websites remove this data when pictures are uploaded, so "none" is common.',
      ''] : []),
    ...(o.postPictures ? ['post-pictures.txt',
      '    This post holds ' + o.postPictures + ' pictures (a slideshow). The web address of each one,',
      '    since only the picture on screen is in the screenshots.',
      ''] : []),
    ...(o.who && o.who.length ? ['who/',
      '    Who is behind it: ' + o.who.map(w => w.label + ' (' + w.name.replace(/^who\//, '') + ')').join(', ') + '.',
      '    Each page was captured the same way as the main page, straight after it, and is covered',
      '    by the same fingerprints and trusted timestamps as everything else in this pack.',
      ''] : []),
    ...(o.hasLookups ? ['lookups/',
      '    Public registration records (RDAP, the official replacement for WHOIS) for the',
      '    website\'s domain and server: who hosts the site and the domain registrar, as',
      '    published at the time of capture.',
      ''] : []),
    'VERIFY-THIS-PACK.html',
    '    A checker that runs every fingerprint and timestamp check in your browser. It is',
    '    itself covered by the fingerprints and timestamps, so it cannot be swapped unnoticed.',
    '',
    'capture-details.txt',
    '    Everything recorded about the capture: address, title, times, browser, case details,',
    '    the website server\'s IP address and response, and a fingerprint for every file.',
    '',
    'fingerprints.sha256',
    '    A SHA-256 fingerprint (a unique 64-character code) for the PDF, HTML, source and',
    '    image files. If even one letter or pixel of a file changes, its fingerprint',
    '    changes completely.',
    '',
    ...(tsa ? ['timestamps/',
      '    Trusted timestamp receipts (.tsr) and the requests that produced them (.tsq).',
      '    Independent timestamp services each digitally signed the fingerprint list,',
      '    using their own clocks:',
      ...stamps.map(t => '      ' + t.service + ': ' + (t.time || 'see receipt') + ' (UTC)  ->  timestamps/' + t.file + '.tsr'),
      '    This proves the files existed in exactly this form at that time. Only the',
      '    fingerprint was sent to the services, never the files themselves.',
      ''] : ['(No trusted timestamp was available when this pack was made. See capture-details.txt.)', '']),
    'README.txt',
    '    This guide. It is the same for every pack, so it is not part of the fingerprint list.',
    '',
    ...ppReadmeChecks(stamps),
  ].join('\r\n');
}

// The "how to check by hand" and "keep it safe" part, shared by page and image packs.
function ppReadmeChecks(stamps) {
  const tsa = stamps.length > 0;
  const certs = { DigiCert: '"DigiCert Trusted Root G4" from https://www.digicert.com/kb/digicert-root-certificates.htm',
    Sectigo: '"USERTrust RSA Certification Authority" root, from sectigo.com',
    FreeTSA: 'https://freetsa.org/files/cacert.pem',
    GlobalSign: '"GlobalSign Root CA - R6" from https://support.globalsign.com/ca-certificates/root-certificates/globalsign-root-certificates',
    Entrust: '"Entrust Root Certification Authority - G2" from https://www.entrust.com/resources/certificate-solutions/tools/root-certificate-downloads' };
  return [
    'HOW TO CHECK BY HAND (INDEPENDENT OF PAGEPROOF)',
    '-----------------------------------------------',
    '',
    'Step 1: Check every file against its fingerprint.',
    '  Open a terminal in this folder (Mac/Linux: Terminal. Windows: "Git Bash" from',
    '  https://git-scm.com/download/win) and run:',
    '',
    '      sha256sum -c fingerprints.sha256          (Windows Git Bash / Linux)',
    '      shasum -a 256 -c fingerprints.sha256      (Mac)',
    '',
    '  Every line should end in "OK".',
    '',
    ...(tsa ? [
      'Step 2: Check a trusted timestamp.',
      '  Download the root certificate of one of the services above into this folder',
      '  and name it cacert.pem:',
      ...stamps.map(t => '      ' + t.service + ': ' + certs[t.service]),
      '  Then run (using that service\'s receipt):',
      '',
      '      openssl ts -verify -in timestamps/' + stamps[0].file + '.tsr -data fingerprints.sha256 -CAfile cacert.pem',
      '',
      '  "Verification: OK" means the service really signed this exact fingerprint list.',
      '  To see the signed date and time:',
      '',
      '      openssl ts -reply -in timestamps/' + stamps[0].file + '.tsr -text',
      '',
      'Together, steps 1 and 2 show that every file is unchanged since the time signed by',
      'the timestamp service.',
      ''] : []),
    'HOW TO KEEP THIS PACK SAFE',
    '--------------------------',
    '',
    '- Keep the zip file as it is. Opening files is fine, but editing or re-saving them',
    '  breaks their fingerprints.',
    '- Keep a second copy on a separate drive or other storage.',
    '- The fingerprint of this whole zip is recorded in the collector\'s PageProof capture log.',
    ''
  ];
}

